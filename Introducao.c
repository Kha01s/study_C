// diz a C para incluir o arquivo de cabeçalho, permitindo usar funções de entrada e saída
#include <stdio.h>
// main() é uma função especial, apenas os códigos dentro dos {} serão executados
int main(){
    // o printf retorna ao usuário uma mensagem
    printf("Olá mundo!\n");
    // \n para quebra de linha
    printf("Estou aprendendo linguagem C");
    // cada declaração em C termina com ;
    return 0;
    // finaliza o main() e envia um valor de volta para o SO
}